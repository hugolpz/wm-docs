<template>
  <div id="wmg-wmfr-spendings" class="spendings-wrapper">
    <div id="wmg-wmfr-spendings-header" class="spendings-header">
      <h2>
        WMFR's public spendings
        <a
          id="wmg-wmfr-spendings-commons"
          class="commons-link"
          href="https://commons.wikimedia.org/wiki/Category:Wikimedia_France_expenses"
          target="_blank"
          rel="noopener"
          title="Source PDFs on Wikimedia Commons"
        >
          <img :src="commonsLogo" alt="Wikimedia Commons" />
        </a>
      </h2>
      <div class="subtitle-row">
        <p class="subtitle">Showing {{ paginatedData.length }} of {{ filteredData.length }} results</p>
        <label id="wmg-wmfr-spendings-regex" class="regex-toggle" title="Treat the filters as case-insensitive regular expressions">
          <input v-model="useRegex" type="checkbox" />
          Regex
        </label>
      </div>
    </div>

    <div id="wmg-wmfr-spendings-table" class="table-container">
      <table class="spendings-table">
        <thead>
          <tr>
            <th v-for="col in columns" :key="col" class="th-styled">
              <div class="col-name">{{ col }}</div>
              <input 
                v-model="filters[col]" 
                type="text" 
                :placeholder="'Filter ' + col + (useRegex ? ' (regex)...' : '...')" 
                class="col-filter" 
                :class="{ 'col-filter-invalid': invalidCols.has(col) }"
                :title="invalidCols.has(col) ? 'Invalid regular expression' : undefined"
              />
            </th>
          </tr>
        </thead>
        <tbody>
          <tr v-for="(row, idx) in paginatedData" :key="idx" class="tr-styled">
            <td v-for="col in columns" :key="col" class="td-styled">
              <!-- Source holds a trusted <a> generated by scripts/extract.py -->
              <span v-if="col === 'Source'" v-html="row[col]"></span>
              <template v-else>{{ row[col] }}</template>
            </td>
          </tr>
          <tr v-if="paginatedData.length === 0">
            <td :colspan="columns.length" class="empty-state">
              No matching records found.
            </td>
          </tr>
        </tbody>
        <tfoot v-if="hasActiveFilter && paginatedData.length > 0">
          <tr class="tfoot-row">
            <td class="td-styled tfoot-label">Total :</td>
            <td class="td-styled tfoot-total">
              {{ formattedTotal }}
            </td>
            <td :colspan="columns.length - 2" class="td-styled"></td>
          </tr>
        </tfoot>
      </table>
    </div>
  </div>
</template>

<script setup>
import { ref, computed, watch } from 'vue';
import { useRoute, useRouter } from 'vue-router';
import spendingsData from '../data/spendings_data.json';
import commonsLogo from '../assets/Commons-logo.svg';

const rawData = spendingsData;
const columns = [
  "Date", 
  "Montant TTC", 
  "Motif", 
  "Projet associé", 
  "Personne associée", 
  "Identifiant",
  "Source"
];

// URL query parameter for each column filter, e.g. ?project=wikipages&date=2024
const QUERY_PARAMS = {
  "Date": "date",
  "Montant TTC": "amount",
  "Motif": "reason",
  "Projet associé": "project",
  "Personne associée": "person",
  "Identifiant": "id",
  "Source": "source"
};

const route = useRoute();
const router = useRouter();

const readFilters = () =>
  Object.fromEntries(columns.map(col => [col, String(route.query[QUERY_PARAMS[col]] ?? "")]));

const filters = ref(readFilters());

// ?regex=1 switches the filters from "contains" to regular expressions
const useRegex = ref(route.query.regex === '1');

// Filters -> URL (replace, so typing doesn't fill the history)
watch(filters, (value) => {
  const query = { ...route.query };
  for (const col of columns) {
    const param = QUERY_PARAMS[col];
    if (value[col].trim()) query[param] = value[col];
    else delete query[param];
  }
  if (useRegex.value) query.regex = '1';
  else delete query.regex;
  router.replace({ query });
}, { deep: true });

watch(useRegex, () => {
  const query = { ...route.query };
  if (useRegex.value) query.regex = '1';
  else delete query.regex;
  router.replace({ query });
});

// URL -> filters (back/forward, pasted links)
watch(() => route.query, () => {
  const fromUrl = readFilters();
  if (columns.some(col => fromUrl[col] !== filters.value[col])) filters.value = fromUrl;
  useRegex.value = route.query.regex === '1';
});

const hasActiveFilter = computed(() => {
  return columns.some(col => filters.value[col].trim() !== '');
});

// Regex mode: one compiled RegExp per filled column; a column whose pattern doesn't compile is
// flagged and matches nothing, so a half-typed pattern never throws.
const regexes = computed(() => {
  const compiled = {};
  const invalid = new Set();
  if (useRegex.value) {
    for (const col of columns) {
      const pattern = filters.value[col].trim();
      if (!pattern) continue;
      try {
        compiled[col] = new RegExp(pattern, 'i');
      } catch {
        invalid.add(col);
      }
    }
  }
  return { compiled, invalid };
});
const invalidCols = computed(() => regexes.value.invalid);

const filteredData = computed(() => {
  return rawData.filter(row => {
    return columns.every(col => {
      const filterValue = filters.value[col].toLowerCase();
      if (!filterValue.trim()) return true;
      // Source cells hold HTML: filter on their visible text only
      const text = String(row[col] || '').replace(/<[^>]*>/g, '');
      if (useRegex.value) {
        const re = regexes.value.compiled[col];
        return re ? re.test(text) : false;
      }
      return text.toLowerCase().includes(filterValue);
    });
  });
});

// "displaying 100 entries"
const paginatedData = computed(() => {
  return filteredData.value.slice(0, 100);
});

// compute the total for Montant TTC column when filtered
const filteredTotal = computed(() => {
  if (!hasActiveFilter.value) return 0;
  
  return filteredData.value.reduce((acc, row) => {
    let valStr = row["Montant TTC"] || "";
    // Remove characters like '€' or spaces, and replace comma with dot for float parsing
    let numericStr = valStr.replace(/[^\d,\.-]/g, '').replace(',', '.');
    let num = parseFloat(numericStr);
    return acc + (isNaN(num) ? 0 : num);
  }, 0);
});

const formattedTotal = computed(() => {
  // Format the number similar to French currency format
  return filteredTotal.value.toLocaleString('fr-FR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }) + ' €';
});
</script>

