<script setup>
import { ref, computed, watch } from 'vue';
import { useRoute, useRouter } from 'vue-router';
import DateRange from './DateRange.vue';
import spendingsData from '../data/spendings_data.json';
import commonsLogo from '../assets/Commons-logo.svg';

const rawData = spendingsData;
const columns = [
  "Date", 
  "Montant TTC", 
  "Motif", 
  "Projet associé", 
  "Personne associée", 
  "Identifiant",
  "Source"
];

// URL query parameter for each column filter, e.g. ?project=wikipages&date=2024
// (?from=2023Q1&to=2024Q4 is the quarter range, handled by DateRange)
const QUERY_PARAMS = {
  "Date": "date",
  "Montant TTC": "amount",
  "Motif": "reason",
  "Projet associé": "project",
  "Personne associée": "person",
  "Identifiant": "id",
  "Source": "source"
};

const route = useRoute();
const router = useRouter();

const readFilters = () =>
  Object.fromEntries(columns.map(col => [col, String(route.query[QUERY_PARAMS[col]] ?? "")]));

const filters = ref(readFilters());

// ?regex=1 switches the filters from "contains" to regular expressions
const useRegex = ref(route.query.regex === '1');

// Filters -> URL (replace, so typing doesn't fill the history)
watch(filters, (value) => {
  const query = { ...route.query };
  for (const col of columns) {
    const param = QUERY_PARAMS[col];
    if (value[col].trim()) query[param] = value[col];
    else delete query[param];
  }
  if (useRegex.value) query.regex = '1';
  else delete query.regex;
  router.replace({ query });
}, { deep: true });

watch(useRegex, () => {
  const query = { ...route.query };
  if (useRegex.value) query.regex = '1';
  else delete query.regex;
  router.replace({ query });
});

// URL -> filters (back/forward, pasted links)
watch(() => route.query, () => {
  const fromUrl = readFilters();
  if (columns.some(col => fromUrl[col] !== filters.value[col])) filters.value = fromUrl;
  useRegex.value = route.query.regex === '1';
});

// Regex mode: one compiled RegExp per filled column; a column whose pattern doesn't compile is
// flagged and matches nothing, so a half-typed pattern never throws.
const regexes = computed(() => {
  const compiled = {};
  const invalid = new Set();
  if (useRegex.value) {
    for (const col of columns) {
      const pattern = filters.value[col].trim();
      if (!pattern) continue;
      try {
        compiled[col] = new RegExp(pattern, 'i');
      } catch {
        invalid.add(col);
      }
    }
  }
  return { compiled, invalid };
});
const invalidCols = computed(() => regexes.value.invalid);

// { from, to } from the quarter slider, null while the whole period is selected
const dateRange = ref(null);

// Slider -> URL: ?from=2023Q1&to=2024Q4, each omitted at its axis edge
const onDateChange = ({ from, to, range }) => {
  dateRange.value = range;
  const query = { ...route.query };
  if (from) query.from = from;
  else delete query.from;
  if (to) query.to = to;
  else delete query.to;
  const same = (k) => String(query[k] ?? '') === String(route.query[k] ?? '');
  if (!same('from') || !same('to')) router.replace({ query });
};

const inDateRange = (row) => {
  if (!dateRange.value) return true;
  const m = String(row["Date"] ?? '').match(/^(\d{4})[/-](\d{1,2})[/-](\d{1,2})/);
  if (!m) return false;
  const t = Date.UTC(+m[1], +m[2] - 1, +m[3]);
  return t >= dateRange.value.from && t <= dateRange.value.to;
};

const filteredData = computed(() => {
  return rawData.filter(row => {
    if (!inDateRange(row)) return false;
    return columns.every(col => {
      const filterValue = filters.value[col].toLowerCase();
      if (!filterValue.trim()) return true;
      // Source cells hold HTML: filter on their visible text only
      const text = String(row[col] || '').replace(/<[^>]*>/g, '');
      if (useRegex.value) {
        const re = regexes.value.compiled[col];
        return re ? re.test(text) : false;
      }
      return text.toLowerCase().includes(filterValue);
    });
  });
});

// "displaying 100 entries"
const paginatedData = computed(() => {
  return filteredData.value.slice(0, 100);
});

// "1 234,56 €" -> 1234.56 (0 when unparseable)
const parseAmount = (valStr) => {
  // Remove characters like '€' or spaces, and replace comma with dot for float parsing
  const num = parseFloat(String(valStr || "").replace(/[^\d,\.-]/g, '').replace(',', '.'));
  return isNaN(num) ? 0 : num;
};

// Total of the Montant TTC column over the filtered rows (all rows when nothing is filtered)
const filteredTotal = computed(() => {
  return filteredData.value.reduce((acc, row) => acc + parseAmount(row["Montant TTC"]), 0);
});

// Intro figures cover the whole dataset, whatever the filters
const introTotal = new Intl.NumberFormat('fr-FR', { style: 'currency', currency: 'EUR', maximumFractionDigits: 0 })
  .format(rawData.reduce((acc, row) => acc + parseAmount(row["Montant TTC"]), 0));
const introProjects = new Set(rawData.map(row => row["Projet associé"]).filter(Boolean)).size.toLocaleString('fr-FR');
const years = rawData.map(row => String(row["Date"]).slice(0, 4)).filter(Boolean).sort();
const introFirstYear = years[0];
const introLastYear = years[years.length - 1];

const formattedTotal = computed(() => {
  // Format the number similar to French currency format
  return filteredTotal.value.toLocaleString('fr-FR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }) + ' €';
});

// Download every filtered row (not only the 100 displayed) as a JSON file
const exportJson = () => {
  const blob = new Blob([JSON.stringify(filteredData.value, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'wmfr-spendings.json';
  a.click();
  URL.revokeObjectURL(url);
};
</script>

